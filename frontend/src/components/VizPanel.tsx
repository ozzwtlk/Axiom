import { useEffect, useState } from "react";
import { ApiError, getVisualization, makeVisualization, visualizationHtmlUrl } from "../api/client";
import { getModelChoice } from "../lib/models";
import { ModelPicker } from "./ModelPicker";
import type { Visualization } from "../api/types";
import { Md } from "./Md";

/**
 * AI-generated interactive visualization. The code runs only inside a sandboxed iframe: no
 * `allow-same-origin` (opaque origin: no access to this app, its cookies, storage or API) and the server
 * serves it with a CSP that blocks all network access.
 */
export function VizPanel({ unitId }: { unitId: string }) {
  const [viz, setViz] = useState<Visualization | null>(null);
  const [state, setState] = useState<"loading" | "none" | "generating" | "ready" | "error">("loading");
  const [error, setError] = useState("");
  const [nonce, setNonce] = useState(0);

  useEffect(() => {
    let alive = true;
    getVisualization(unitId)
      .then((v) => alive && (setViz(v), setState("ready")))
      .catch((e) => alive && (e instanceof ApiError && e.status === 404 ? setState("none") : (setError(String(e)), setState("error"))));
    return () => {
      alive = false;
    };
  }, [unitId]);

  const generate = (regenerate = false) => {
    setState("generating");
    makeVisualization(unitId, regenerate, getModelChoice("visualize"))
      .then((v) => (setViz(v), setNonce((n) => n + 1), setState("ready")))
      .catch((e) => (setError(e instanceof Error ? e.message : String(e)), setState("error")));
  };

  return (
    <div className="viz-panel">
      {state === "loading" && <p className="muted">Loading…</p>}
      {state === "none" && (
        <p>
          <button type="button" className="btn btn-sm" onClick={() => generate()}>
            Generate visualization
          </button>{" "}
          <ModelPicker group="visualize" compact />{" "}
          <span className="muted small">Written by AI, checked by a second model, runs in a sandbox.</span>
        </p>
      )}
      {state === "generating" && <p className="muted">Generating and reviewing… (local: a few minutes)</p>}
      {state === "error" && (
        <p className="error">
          {error}{" "}
          <button type="button" className="link-btn" onClick={() => generate(true)}>
            try again
          </button>
        </p>
      )}
      {state === "ready" && viz && (
        <>
          <div className="viz-head">
            <span className="ai-tag" title="Generated by AI; illustrative, check against the text">
              AI visualization
            </span>{" "}
            {viz.reviewed ? (
              <span className="checked" title="An independent AI review traced the drawing code against the passage; it can still miss errors">
                ✓ reviewed
              </span>
            ) : (
              <span className="flag-chip" title="Generated before independent review existed">unreviewed</span>
            )}{" "}
            <strong>{viz.title}</strong>
          </div>
          <Md src={viz.description_md} />
          {viz.review_notes && viz.review_notes.length > 0 && (
            <details className="small viz-notes">
              <summary>Reviewer notes ({viz.review_notes.length})</summary>
              <ul>
                {viz.review_notes.map((n, i) => (
                  <li key={i}>{n}</li>
                ))}
              </ul>
            </details>
          )}
          <iframe
            key={nonce}
            className="viz-frame"
            title={viz.title}
            src={visualizationHtmlUrl(unitId)}
            sandbox="allow-scripts"
            referrerPolicy="no-referrer"
            loading="lazy"
          />
          <button type="button" className="link-btn" onClick={() => generate(true)}>
            regenerate
          </button>
        </>
      )}
    </div>
  );
}
